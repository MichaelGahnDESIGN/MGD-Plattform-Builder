    /** @param array<string,string|int> $params */
    public function t(string $key, array $params = []): string
    {
        $table = $this->locale === 'en' ? self::EN : self::DE;
        $text = $table[$key] ?? self::DE[$key] ?? $key;

        foreach ($params as $name => $value) {
            $text = str_replace('{' . $name . '}', (string) $value, $text);
        }

        return $text;
    }

    /** Alle Schluessel der Sprache (fuer die Konsistenzpruefung DE/EN im Test). @return list<string> */
    public static function keys(string $locale): array
    {
        return array_keys($locale === 'en' ? self::EN : self::DE);
    }

    /** Text zu einem Fehlercode des Katalogs (Failure::CODES). */
    public function code(?string $code): string
    {
        if ($code === null || $code === '') {
            return $this->t('none');
        }

        return $this->t('code_' . $code);
    }
